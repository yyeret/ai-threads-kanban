function titleFrom(text) {
  const cleaned = clean(text);
  if (!cleaned) return "Untitled session";
  return sentenceCase(truncate(cleaned.replace(/^<[^>]+>/, ""), 70));
}

// Turn a raw first user message into a short action-oriented title.
// Claude has no equivalent of Codex's thread_name, so titles come from the
// prompt itself. The first message often opens with a paste (markdown doc,
// git status, code fence) before the actual question — walk forward through
// paragraphs to find the first one that looks like the user's own intent.
function claudeTitleFromPrompt(text) {
  let raw = String(text || "").trim();
  if (!raw) return "";
  // Take blocks separated by blank lines; pick the first that isn't a paste.
  const blocks = raw.split(/\n\s*\n+/).map((s) => s.trim()).filter(Boolean);
  const goodBlock = blocks.find((b) => !looksLikePaste(b));
  if (!goodBlock) return ""; // every block looks like tool output / paste — no usable title
  let s = goodBlock;
  // Within the chosen block, take the first non-paste line.
  const firstLine = s.split(/\n/).map((l) => l.trim()).find((l) => l && !looksLikePaste(l)) || s;
  s = clean(firstLine);
  // Strip leading line-number or "N #" prefix before heading markers.
  s = s.replace(/^\d+\s+/, "");
  // Strip leading markdown heading markers (# / ## / ...) but keep the title.
  s = s.replace(/^#+\s*/, "");
  s = s.replace(/^<[^>]+>\s*/g, "");
  s = s.replace(/https?:\/\/\S+/g, "").trim();
  // Drop conversational lead-ins so the verb starts the title.
  s = s.replace(
    /^(hey|hi|ok|okay|so|um|please|pls|kindly|let'?s|lets|can you|could you|would you|will you|i'?d like (you )?to|i want (you )?to|i need (you )?to|i'?m (going to|gonna)|help me|help us|maybe|just)\s+/i,
    "",
  );
  // Take the first sentence / clause to keep titles tight.
  const m = s.match(/^[^.?!\n]{3,200}/);
  if (m) s = m[0];
  return clean(s);
}

// True if a paragraph looks like pasted content rather than the user's words:
// git status / branch output, code fences, JSON/JSONL, log lines, "modified:",
// or a long block whose first non-blank char is punctuation/markup.
function looksLikePaste(block) {
  const t = String(block || "").trim();
  if (!t) return true;
  if (/^```/.test(t)) return true;
  if (/^On branch \S+/i.test(t)) return true;
  if (/^(modified|new file|deleted|renamed):/im.test(t)) return true;
  if (/^[{[]/.test(t) && t.length > 200) return true;       // JSON dump
  if (/^\[object Object\]/.test(t)) return true;            // serialised JS object
  if (/^\s*\d{4}-\d{2}-\d{2}T\d{2}/.test(t)) return true;   // ISO log line
  if (/^[A-Za-z]:\\/.test(t) && t.includes("\\")) return true; // pasted Windows path
  if (/^(File content \(|File does not exist|Exit code \d|InputValidationError|<tool_use_error>)/i.test(t)) return true; // tool error/size msgs
  if (/^@\//.test(t)) return true;                           // @/path pasted file ref
  // Code line: leading line-number + identifier, or "identifier = value" / "identifier(args)"
  if (/^\d+\s+[a-z_$][\w$]*[\s(=<>!]/.test(t)) return true; // "153 const foo ="
  // Directory listing / multi-file paste: two or more filename-like tokens
  // (something.ext) with no verb-shaped tokens around them.
  const fileLikes = (t.match(/\b[\w-]+\.[a-z]{1,5}\b/g) || []).length;
  if (fileLikes >= 3 && t.length < 400) return true;
  // Single line that's nothing but a filename/slug — "AGENTS", "Article-draft",
  // "Ai_leadership_filtered", "10-how-to-..." — no spaces, no verbs.
  if (!/\s/.test(t) && /^[\w.\-]+$/.test(t)) return true;
  // Trailing punctuation that looks like the start of a paste block.
  if (/^Actions[/:\\]/.test(t)) return true;
  return false;
}

function clean(text) {
  return String(text || "").replace(/\s+/g, " ").trim();
}

function isSubstantivePrompt(text) {
  const cleaned = clean(text).toLowerCase();
  if (!cleaned) return false;
  const skipPrefixes = [
    "<environment_context>",
    "<local-command-caveat>",
    "<ide_opened_file>",
    "<ide_selection>",
    "<system-reminder>",
    "<command-name>",
    "<command-message>",
    "<command-args>",
    "<local-command-stdout>",
    "<local-command-stderr>",
    "# agents.md instructions",
    "# claude.md",
    "# context from my ide setup",
    "# files mentioned by the user",
    "workspace context to honor",
    "codebase and user instructions",
    "<tool_use_error>",
  ];
  if (skipPrefixes.some((prefix) => cleaned.startsWith(prefix))) return false;
  // Codex/Claude inject repo instruction blocks as the first "user" turn.
  if (cleaned.includes("<instructions>") && cleaned.length > 400) return false;
  return true;
}

// Returns the real user request, stripped of injected IDE-context wrappers,
// or null if the turn is not a substantive prompt.
function substantivePrompt(raw) {
  let text = clean(raw);
  if (!text) return null;
  const marker = text.match(/##\s*my request(?: for [a-z]+)?\s*:?\s*/i);
  if (marker) text = clean(text.slice(marker.index + marker[0].length));
  if (!text || !isSubstantivePrompt(text)) return null;
  return text;
}

function truncate(text, length) {
  const cleaned = clean(text);
  return cleaned.length > length ? `${cleaned.slice(0, length - 3)}...` : cleaned;
}

function sentenceCase(text) {
  const cleaned = clean(text);
  return cleaned ? cleaned[0].toUpperCase() + cleaned.slice(1) : "";
}

function shortId(id) {
  return String(id || "unknown").slice(0, 8);
}

function stripStagePrefix(text) {
  return String(text || "").replace(/^\s*\[[^\]]{1,24}\]\s*/, "");
}

function compact(values) {
  return values.filter((value) => value !== undefined && value !== null && String(value).trim());
}

function escapeMd(text) {
  return String(text || "").replace(/\|/g, "\\|");
}

function expandHome(value) {
  if (!value) return value;
  if (value === "~") return home;
  if (value.startsWith("~/") || value.startsWith("~\\")) return path.join(home, value.slice(2));
  return value;
}

function safeFileName(value) {
  return String(value || "unknown")
    .trim()
    .replace(/[^a-z0-9._-]+/gi, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80) || "unknown";
}
